#!/usr/bin/env python3
"""Regenerate BERT's fixed Mn predicate using Python's Unicode 15.0.0 data."""
from pathlib import Path
import unicodedata

if unicodedata.unidata_version != "15.0.0":
    raise RuntimeError("Use a Python build with Unicode 15.0.0; changing categories requires a tokenizer version bump")
ranges = []
for value in range(0x110000):
    if unicodedata.category(chr(value)) != "Mn":
        continue
    if ranges and ranges[-1][1] + 1 == value:
        ranges[-1][1] = value
    else:
        ranges.append([value, value])
destination = Path(__file__).resolve().parents[1] / "drummer/src/UnicodeMarks.h"
destination.write_text("""#pragma once
#include <array>
#include <cstdint>

// Generated by native/tools/generate-unicode-marks.py using Unicode 15.0.0.
// A fixed category table preserves spacing/enclosing marks during BERT accent stripping.
namespace drummer {
inline constexpr std::array<std::array<uint32_t, 2>, %d> nonspacingMarks {{
%s
}};
}
""" % (len(ranges), "\n".join("    {0x%x, 0x%x}," % tuple(row) for row in ranges)))
print(destination)
