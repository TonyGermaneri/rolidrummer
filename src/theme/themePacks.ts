/**
 * More themes: 70s–90s video games, home computers, movies, TV and eras. Palettes are nods, not replicas.
 * `th()` keeps each one to a few lines; the fields are the same as the hand-written themes in themes.ts.
 */
import type { Theme, ThemeGroup } from './themes'

type Five = [string, string, string, string, string]
type Three = [string, string, string]

/** colours: primary, secondary, accent, success, danger · lcd: [background, idle] · pad: [saturation %, lightness %] */
function th(
  group: ThemeGroup,
  id: string,
  name: string,
  colors: Five,
  panel: Three,
  bg: Three,
  wood: Three,
  text: Five,
  lcd: [string, string],
  logo: Three,
  padHues: number[],
  pad: [number, number],
): Theme {
  const [primary, secondary, accent, success, danger] = colors
  return {
    id, name, group, primary, secondary, accent, success, danger, panel, bg, wood, text,
    lcd: lcd[0], lcdIdle: lcd[1], logo, padHues, padSat: pad[0], padLight: pad[1],
  }
}

